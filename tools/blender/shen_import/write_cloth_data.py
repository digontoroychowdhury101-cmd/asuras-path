"""Write src/shared/ShenClothData.luau from work/shen_import/cloth_p<n>.json (skin_rig.py): the skeleton and cloth lattice each form's client simulation needs.

    python3 tools/blender/shen_import/write_cloth_data.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../.."))


def lua(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return '"%s"' % v
    if isinstance(v, (list, tuple)):
        return "{" + ",".join(lua(x) for x in v) + "}"
    return "{" + ",".join("%s=%s" % (k, lua(x)) for k, x in v.items()) + "}"


def main():
    out = ["--!strict", "-- ModuleScript: ReplicatedStorage/AsurasPath/Shared/ShenClothData",
           "-- Generated by tools/blender/shen_import/write_cloth_data.py from the sculpts (skin_rig.py). Do not edit: rest points are in rig studs at scale 1, per form.",
           "local Data: { [number]: any } = {}"]
    for phase in (1, 2):
        c = json.load(open(os.path.join(ROOT, f"work/shen_import/cloth_p{phase}.json")))
        keep = {k: c[k] for k in ("bones", "sheets", "particles", "links", "colliders", "hits", "limbs", "grip", "skin") if k in c}
        out.append("Data[%d] = %s" % (phase, lua(keep)))
    out.append("return Data\n")
    path = os.path.join(ROOT, "src/shared/ShenClothData.luau")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print(path, os.path.getsize(path), "bytes")


if __name__ == "__main__":
    main()
