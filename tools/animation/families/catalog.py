"""Writes src/shared/AnimationFamilyIds.luau from assets/animations/families/published.json.

    python3 tools/animation/families/catalog.py

Only a clip whose record matches the current .rbxmx content goes in, so the game never names an asset it was not published from.
A family clip's slot "Dao.Light1" lands in Weapons.Dao.Light1, a universal's slot "DashLeft" in Universal.DashLeft.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BASE = ROOT / "assets/animations/families"


def main():
    manifest = json.loads((BASE / "manifest.json").read_text())["clips"]
    published = json.loads((BASE / "published.json").read_text())["clips"]
    weapons, universal, stale = {}, {}, []
    for name, entry in sorted(manifest.items()):
        record = published.get(name)
        if not record or record["sha256"] != entry["sha256"]:
            stale.append(name)
            continue
        if "." in entry["slot"]:
            weapon, key = entry["slot"].split(".")
            weapons.setdefault(weapon, {})[key] = record["asset_id"]
        else:
            universal[entry["slot"]] = record["asset_id"]
    lines = ["--!strict", "-- GENERATED by tools/animation/families/catalog.py from assets/animations/families/published.json. Do not edit.",
             "-- Read back after upload; AnimationCatalog applies these to its weapon and universal slots.", "return {", "\tWeapons = {"]
    for weapon in sorted(weapons):
        lines.append("\t\t%s = {" % weapon)
        lines.extend('\t\t\t%s = "%s",' % (k, v) for k, v in sorted(weapons[weapon].items()))
        lines.append("\t\t},")
    lines += ["\t},", "\tUniversal = {"]
    lines.extend('\t\t%s = "%s",' % (k, v) for k, v in sorted(universal.items()))
    lines += ["\t},", "}"]
    (ROOT / "src/shared/AnimationFamilyIds.luau").write_text("\n".join(lines) + "\n")
    print("%d weapons, %d universal, not published: %s" % (len(weapons), len(universal), stale or "none"))


if __name__ == "__main__":
    main()
