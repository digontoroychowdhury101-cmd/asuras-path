// Offline bake: FastNoiseLite never runs on the game server or changes route geometry.
import FastNoiseLite from '../vendor/fastnoise-lite/FastNoiseLite.js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const noise = new FastNoiseLite(7341);
noise.SetNoiseType(FastNoiseLite.NoiseType.OpenSimplex2S);
noise.SetFrequency(0.009);
noise.SetFractalType(FastNoiseLite.FractalType.Ridged);
noise.SetFractalOctaves(3);
noise.SetFractalGain(0.45);
const rows = [];
for (let z = -640; z >= -1160; z -= 22) {
    const heights = [-1, 1].map(side => {
        const value = noise.GetNoise(side * 198, z);
        if (!Number.isFinite(value)) throw new Error('Non-finite ridge sample');
        return (18 + Math.max(0, Math.min(1, (value + 1) / 2)) * 20).toFixed(4);
    });
    rows.push(`\t{ ${heights.join(', ')} }, -- z = ${z}`);
}
const source = `--!strict
-- Generated by node tools/assets/build_github_terrain.mjs; seed 7341.
-- FastNoiseLite (MIT), Jordan Peck and contributors. See tools/vendor/fastnoise-lite/LICENSE.
-- Only the existing upper cliff balls use these heights; all floors, cuts and routes are authored.
return table.freeze({
${rows.join('\n')}
})
`;
writeFileSync(fileURLToPath(new URL('../../src/shared/MonasteryRidgeProfile.luau', import.meta.url)), source);
console.log(`Baked ${rows.length * 2} coherent monastery ridge heights`);
